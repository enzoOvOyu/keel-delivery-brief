"""Developer-facing field proposals. Does not change executable business contracts."""


def field(name, kind, label, rule, required="必填", status="建议"):
    return dict(name=name, type=kind, label=label, rule=rule, required=required, status=status)


def contract(category, rule, *fields):
    return dict(category=category, rule=rule, fields=list(fields))


