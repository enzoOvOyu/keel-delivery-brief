def attach(reader):
    assert set(CATALOG) == {a["id"] for a in reader["artifacts"]}, "Artifact field catalogue must match the canonical model"
    reader["data_guide"] = dict(
        note="“已有”指沿用字段名；新增字段名与结构为开发约定建议。结合本卡片的模拟数据理解；生产接口 Schema 与业务阈值仍需确认。",
        id_rules=ID_RULES, formats=FORMATS, common_fields=COMMON_FIELDS,
    )
    for artifact in reader["artifacts"]:
        artifact["data_contract"] = CATALOG[artifact["id"]]


def markdown(reader):
    def table(headers, rows):
        clean = lambda x: str(x).replace("|", "／").replace("\n", " ")
        return "\n".join(["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)] + ["| " + " | ".join(clean(x) for x in row) + " |" for row in rows])
    def fields(rows):
        return table(["字段", "含义", "格式", "要求", "约束", "约定"], [[f["name"], f["label"], f["type"], f["required"], f["rule"], f["status"]] for f in rows])
    guide = reader["data_guide"]
    out = ["## 开发数据简表", guide["note"], "### ID 规划", table(["类别", "标识", "规则", "约定"], [[r["name"], r["fields"], r["rule"], r["status"]] for r in guide["id_rules"]]),
           "### 数据格式", "下列类型别名和对象组合为建议约定；既有字段的具体协议保持兼容。", table(["类型", "格式", "要求"], [[r["name"], r["shape"], r["rule"]] for r in guide["formats"]]),
           "### 业务产物通用字段", fields(guide["common_fields"])]
    for artifact in reader["artifacts"]:
        c = artifact["data_contract"]
        out += ["### " + artifact["name"], c["rule"], fields(c["fields"])]
    return "\n\n".join(out)
