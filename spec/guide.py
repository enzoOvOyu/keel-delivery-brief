def attach(reader):
    reader["questions"] = [{"key": key, "title": title} for key, title in QUESTIONS]
    for stage in reader["stages"]:
        stage["brief"] = copy.deepcopy(STAGE_BRIEFS[stage["id"]])
    sample = copy.deepcopy(WIRING)
    for check in sample["checks"]:
        check.pop("source")  # Source anchors live only in the archive traceability index.
    reader["wiring_sample"] = sample


def brief_markdown(brief):
    return "\n".join(f"- **{title}：** {brief[key]}" for key, title in QUESTIONS)


def sample_markdown(sample):
    out = ["## 3.3 完整样板：核对并确认物理接线", sample["intro"], brief_markdown(sample["brief"])]
    out += ["### 责任分工", "| 责任主体 | 执行内容 | 边界 |\n|---|---|---|"]
    out += [f"| {r['actor']} | {r['action']} | {r['boundary']} |" for r in sample["roles"]]
    out += ["### 开始前逐项核对", "| 条件 | 所需证明 | 缺口处理 |\n|---|---|---|"]
    out += [f"| {r['condition']} | {r['evidence']} | {r['gap']} |" for r in sample["admission"]]
    out.append(sample["admission_boundary"])
    for step in sample["steps"]:
        out.append(f"### {step['code']} {step['title']}")
        out += [f"- **{name}：** {step[key]}" for key, name in [("input", "输入"), ("action", "动作"), ("output", "产物"), ("finish", "完成条件"), ("failure", "失败后续")]]
    out += ["### 证据应表达的内容", "以下为契约语义清单；字段命名与存储组织仍可按实现设计。", "| 信息 | 内容 | 消费检查 |\n|---|---|---|"]
    out += [f"| {r['name']} | {r['meaning']} | {r['check']} |" for r in sample["evidence_fields"]]
    out += ["### 与下一步交接", "| 当前事实 | 含义 | 后续 |\n|---|---|---|"]
    out += [f"| {r['event']} | {r['meaning']} | {r['next']} |" for r in sample["handoff"]]
    out += ["### 失败与恢复", sample["recovery_boundary"], "| 问题 | 处理 | 返回位置 |\n|---|---|---|"]
    out += [f"| {r['problem']} | {r['action']} | {r['return']} |" for r in sample["recoveries"]]
    out += ["### 情景对照", sample["scenario_context"]]
    for row in sample["scenarios"]:
        out += [f"#### {row['name']}", f"{row['host']} {row['switch']}", f"**端口对：** {row['pair']}\n\n**整步确认：** {row['completion']}\n\n**当前消费：** {row['usable']}\n\n**后续：** {row['next']}"]
